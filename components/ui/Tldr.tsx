"use client";

import { useRef, useState } from "react";
import Image from "next/image";
import { XIcon } from "@phosphor-icons/react/dist/csr/X";
import { cx } from "@/lib/grid";
import notefolio from "@/assets/notefolio.jpg";
import lines from "@/content/notefolio.json";
import { ventures, type Venture } from "@/content/intro";
import { VentureCard } from "./VentureCard";
import chip from "./Chip.module.css";
import styles from "./Tldr.module.css";

type Char = [string | null, number, string | null];
type Line = { left: number; top: number; h: number; chars: Char[] };
type Preview = { venture: Venture; x: number; y: number; open: boolean };

const CARD = 300; // VentureCard width (260 under 520px)
const EDGE = 8;

/**
 * tl;dr: the whole portfolio, handwritten on one notebook page. The photo
 * carries an invisible text layer laid character by character over the ink
 * (generated by wireframe/notefolio/build.py), so the handwriting selects and
 * copies like text.
 */
export function Tldr({ className }: { className?: string }) {
  const dialog = useRef<HTMLDialogElement>(null);
  const frame = useRef<HTMLDivElement>(null);
  const [preview, setPreview] = useState<Preview | null>(null);
  const close = () => dialog.current?.close();

  /** Hovering a TaskLearn / Visume link shows its preview card above the ink, kept inside the photo. */
  const show = (el: HTMLElement) => {
    const venture = ventures.find((v) => el.getAttribute("href")?.startsWith(v.href));
    if (!venture || !frame.current) return;
    const f = frame.current.getBoundingClientRect();
    const r = el.getBoundingClientRect();
    const half = (window.innerWidth < 520 ? 260 : CARD) / 2;
    const x = Math.min(Math.max(r.left + r.width / 2 - f.left, half + EDGE), f.width - half - EDGE);
    setPreview({ venture, x, y: r.top - f.top, open: true });
  };
  const hide = () => setPreview((p) => p && { ...p, open: false });

  return (
    <>
      <button
        type="button"
        className={cx(chip.chip, chip.interactive, className)}
        aria-haspopup="dialog"
        onClick={() => dialog.current?.showModal()}
      >
        tl;dr
      </button>

      <dialog
        ref={dialog}
        className={styles.dialog}
        aria-label="tl;dr: my portfolio on one notebook page"
        // A click on the backdrop (the dialog itself, outside the photo) closes it
        onClick={(e) => e.target === e.currentTarget && close()}
      >
        <div
          ref={frame}
          className={styles.frame}
          onPointerOver={(e) => {
            const a = (e.target as HTMLElement).closest("a");
            if (a) show(a);
          }}
          onPointerOut={(e) => (e.target as HTMLElement).closest("a") && hide()}
          onFocus={(e) => e.target instanceof HTMLAnchorElement && show(e.target)}
          onBlur={hide}
        >
          <Image
            src={notefolio}
            alt="A spiral notebook page with Himanshu's portfolio handwritten in red ink, with doodles of a smiley, stars, shapes and a city skyline."
            className={styles.photo}
            sizes="(max-width: 768px) 100vw, 75vh"
            quality={90}
            draggable={false}
          />
          <div className={styles.transcript}>
            {(lines as unknown as Line[]).map((l, i) => (
              <div
                key={i}
                className={styles.line}
                style={{ "--left": `${l.left}cqi`, "--top": `${l.top}cqi`, "--h": `${l.h}cqi` } as React.CSSProperties}
              >
                {runs(l.chars)}
                <span className={styles.nl}>{"\n"}</span>
              </div>
            ))}
          </div>
          {preview && (
            <div
              className={styles.preview}
              data-open={preview.open ? "" : undefined}
              style={{ left: preview.x, top: preview.y }}
              aria-hidden="true"
            >
              <VentureCard venture={preview.venture} />
            </div>
          )}
          <button type="button" className={styles.close} aria-label="Close" onClick={close}>
            <XIcon weight="bold" />
          </button>
        </div>
      </dialog>
    </>
  );
}

/** Characters grouped so linked runs share one <a>. A null char is crossed-out ink: an unselectable gap. */
function runs(chars: Char[]) {
  const out: React.ReactNode[] = [];
  let i = 0;
  while (i < chars.length) {
    const href = chars[i][2];
    const group: React.ReactNode[] = [];
    for (; i < chars.length && chars[i][2] === href; i++) {
      const [ch, adv] = chars[i];
      const style = { "--adv": `${adv}cqi` } as React.CSSProperties;
      group.push(
        ch === null ? <span key={i} className={styles.gap} style={style} /> : <span key={i} style={style}>{ch}</span>,
      );
    }
    out.push(
      href ? (
        <a key={i} href={href} {...(href.startsWith("mailto") ? {} : { target: "_blank", rel: "noopener" })}>
          {group}
        </a>
      ) : (
        group
      ),
    );
  }
  return out;
}
