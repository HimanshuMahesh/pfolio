// Builds the wishlist figures into public/wishlist/<name>-{dark,light}[-live].svg
// and writes components/about/wishlist-figures.ts with their sizes. They share
// the carry strip's harness (scripts/carry/lib.mjs): one scale, one plinth, one look.
//   node scripts/wishlist/build.mjs [--only=<name>] [--preview]
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { write } from "../carry/lib.mjs";
import { THEMES } from "./palette.mjs";
import { gauntlet } from "./gauntlet.mjs";
import { batarang } from "./batarang.mjs";
import { ring } from "./ring.mjs";
import { omnitrix } from "./omnitrix.mjs";
import { portal } from "./portal.mjs";
import { door } from "./door.mjs";
import { masterball } from "./masterball.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const DIR = join(HERE, "../../public/wishlist");
const FIGURES = { gauntlet, batarang, ring, omnitrix, portal, door, masterball };

const only = process.argv.find((arg) => arg.startsWith("--only="))?.slice(7);
const built = [];
for (const [name, build] of Object.entries(FIGURES)) {
  if (only && only !== name) continue;
  built.push(write(name, build(), { dir: DIR, themes: THEMES }));
}

// --preview writes public/wishlist/preview.html (served by `next dev`): each
// figure still and live, in both themes, at 1.5×. Delete it before committing.
if (process.argv.includes("--preview")) {
  const img = (f, theme, live) =>
    `<img src="${f.name}-${theme}${live ? "-live" : ""}.svg" width="${f.width * 1.5}" height="${f.height * 1.5}">`;
  const row = (theme, bg, live) =>
    `<div style="background:${bg};display:flex;gap:24px;align-items:flex-end;padding:24px;flex-wrap:wrap">${built.map((f) => img(f, theme, live)).join("")}</div>`;
  writeFileSync(
    join(DIR, "preview.html"),
    `<!doctype html><body style="margin:0">${row("dark", "#0a0a0b")}${row("dark", "#0a0a0b", true)}${row("light", "#fbf6ec")}${row("light", "#fbf6ec", true)}</body>`,
  );
  console.log("wrote preview.html");
}

if (!only) {
  const manifest = built.map(({ name, width, height, label }) => ({ name, width, height, label }));
  writeFileSync(
    join(HERE, "../../components/about/wishlist-figures.ts"),
    `// Generated by scripts/wishlist/build.mjs. Do not edit by hand.\nexport const WISHLIST_FIGURES = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  );
}
