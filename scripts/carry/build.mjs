// Builds the carry strip figures into public/carry/<name>-{dark,light}.svg and
// writes components/home/carry/figures.ts with their sizes.
//   node scripts/carry/build.mjs [--preview <dir>]
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { write } from "./lib.mjs";
import { camera } from "./camera.mjs";
import { iphone } from "./iphone.mjs";
import { iems } from "./iems.mjs";
import { nswitch } from "./switch.mjs";
import { watch } from "./watch.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const FIGURES = { camera, iphone, iems, switch: nswitch, watch };

const only = process.argv.find((arg) => arg.startsWith("--only="))?.slice(7);
const built = [];
for (const [name, build] of Object.entries(FIGURES)) {
  if (only && only !== name) continue;
  built.push(write(name, build()));
}

const at = process.argv.indexOf("--preview");
if (at > 0) {
  const dir = process.argv[at + 1];
  const rel = join(HERE, "../../public/carry").replace(/\\/g, "/");
  const row = (theme, bg) =>
    `<div style="background:${bg};display:flex;gap:24px;align-items:flex-end;padding:24px;flex-wrap:wrap">${built
      .map((f) => `<img src="/carry/${f.name}-${theme}.svg" width="${f.width * 1.5}" height="${f.height * 1.5}">`)
      .join("")}</div>`;
  writeFileSync(join(dir, "preview.html"), `<!doctype html><body style="margin:0">${row("dark", "#0a0a0b")}${row("light", "#f5f4f0")}</body>`);
  console.log("wrote preview.html");
}

if (!only) {
  const manifest = built.map(({ name, width, height, label }) => ({ name, width, height, label }));
  writeFileSync(
    join(HERE, "../../components/home/carry/figures.ts"),
    `// Generated by scripts/carry/build.mjs. Do not edit by hand.\nexport const CARRY_FIGURES = ${JSON.stringify(manifest, null, 2)} as const;\n`,
  );
}
